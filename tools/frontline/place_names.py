"""Place-name labels for the Pacific map, written to war3mapLabels.txt inside the map.

The client (client/cl_maplabels.c) loads `<map>\\war3mapLabels.txt` per map and draws each line
`<kind> <x> <y> <name>` (world units, '#' comments). Kinds and when they show:

  sea     large faint water names, zoomed out only
  region  large faint land/area names (mainland, off-map areas), zoomed out
  group   island groups, zoomed out to medium; also on the minimap
  island  one per pacific.ISLANDS shape, medium zoom and closer
  base    harbours, airfields and towns, close zoom

Island labels come from pacific.ISLANDS (arc-length midpoint of each polyline), so new or moved
islands are labelled automatically. Everything else is listed below in lon/lat through pacific.at;
the map thread can add rows to SEAS/REGIONS/GROUPS/BASES or set ISLAND_NAMES/ISLAND_KIND.
"""
import math

from tools.frontline import pacific

KINDS = ('sea', 'region', 'group', 'island', 'base')

# Display names for pacific.ISLANDS keys (wartime English usage); unlisted keys are used as-is.
ISLAND_NAMES = {'Taiwan': 'Formosa'}
# Shapes that are not islands get another kind.
ISLAND_KIND = {'Korea': 'region'}

SEAS = [
    ('Philippine Sea', 138.5, 16.5),
    ('Coral Sea', 155.0, -15.0),
    ('Solomon Sea', 153.5, -8.6),
    ('Bismarck Sea', 149.5, -1.5),
    ('South China Sea', 116.5, 14.0),
    ('East China Sea', 125.0, 30.0),
    ('Sea of Japan', 134.5, 39.5),
    ('Celebes Sea', 121.5, 4.0),
    ('Pacific Ocean', 160.0, 33.0),
    ('Central Pacific', 176.0, 12.0),
]

REGIONS = [
    ('China', 116.5, 29.0),
    ('Manchuria', 120.0, 46.0),
    # North of the playable edge (50N): no land is modelled, the label marks the direction.
    ('Aleutian Islands', 179.0, 48.6),
]

# Groups: name -> members (pacific.ISLANDS keys) and an offset in world units from their centre,
# so the group name sits clear of its island names. List order is declutter priority (the
# minimap only fits a few names), so keep the most important groups first.
GROUPS = [
    ('Japan', ['Kyushu', 'Shikoku', 'Honshu', 'Hokkaido'], (2600, -1600)),
    ('Hawaiian Islands', ['Kauai', 'Oahu', 'Maui', 'Hawaii'], (0, 3600)),
    ('Philippines', ['Luzon', 'Visayas', 'Mindanao'], (2900, 0)),
    ('Solomon Islands', ['Bougainville', 'New Georgia', 'Guadalcanal'], (1400, 1300)),
    ('Mariana Islands', ['Saipan', 'Guam'], (1300, -300)),
    ('Marshall Islands', ['Kwajalein'], (0, 1000)),
    ('Gilbert Islands', ['Tarawa'], (0, 1000)),
    ('Caroline Islands', ['Truk'], (0, 1100)),
    ('Ryukyu Islands', ['Okinawa'], (0, 1100)),
    ('Volcano Islands', ['Iwo Jima'], (0, 1000)),
    ('Bismarck Archipelago', ['New Britain'], (0, 1300)),
]

# Bases: name -> world point. HQs use the scenario sites so the label marks the actual base.
BASES = [
    ('Pearl Harbor', pacific.HQ['USN']),
    ('Yokosuka', pacific.HQ['IJN']),
    ('Kure', pacific.at(132.55, 34.3)),
    ('Tinian', pacific.at(145.6, 15.0)),
    ('Leyte', pacific.at(124.8, 11.0)),
    ('Manila', pacific.at(121.0, 14.6)),
    ('Rabaul', pacific.at(152.1, -4.3)),
    ('Henderson Field', pacific.at(160.1, -9.4)),
    ('Port Moresby', pacific.at(147.2, -9.1)),
    ('Kwajalein Atoll', pacific.at(167.7, 8.3)),
    ('Betio', pacific.at(173.0, 0.7)),
]


def island_point(points):
    """Arc-length midpoint of an island polyline (the point itself for round islands)."""
    if len(points) == 1:
        return points[0]
    lengths = [math.dist(a, b) for a, b in zip(points, points[1:])]
    half = sum(lengths) / 2
    for (a, b), length in zip(zip(points, points[1:]), lengths):
        if half <= length and length:
            t = half / length
            return (round(a[0] + (b[0] - a[0]) * t), round(a[1] + (b[1] - a[1]) * t))
        half -= length
    return points[-1]


def labels():
    """[(kind, x, y, name)] in drawing priority order within each kind."""
    rows = [('sea', *pacific.at(lon, lat), name) for name, lon, lat in SEAS]
    rows += [('region', *pacific.at(lon, lat), name) for name, lon, lat in REGIONS]
    centres = {name: island_point(points) for name, (points, _) in pacific.ISLANDS.items()}
    for name, members, (dx, dy) in GROUPS:
        cx = sum(centres[m][0] for m in members) / len(members)
        cy = sum(centres[m][1] for m in members) / len(members)
        rows.append(('group', round(cx + dx), round(cy + dy), name))
    for key, (x, y) in centres.items():
        rows.append((ISLAND_KIND.get(key, 'island'), x, y, ISLAND_NAMES.get(key, key)))
    rows += [('base', x, y, name) for name, (x, y) in BASES]
    order = {kind: i for i, kind in enumerate(KINDS)}
    return sorted(rows, key=lambda row: order[row[0]])


def text(rows=None):
    out = ['# Place-name labels: <kind> <x> <y> <name>; kinds: ' + ', '.join(KINDS) +
           '. Generated by tools/frontline/place_names.py.']
    out += [f'{kind} {x} {y} {name}' for kind, x, y, name in (rows if rows is not None else labels())]
    return '\n'.join(out) + '\n'
